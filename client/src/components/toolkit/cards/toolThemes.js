/**
 * Safely resolves the category theme token object for any given category string.
 * @param {string} [category]
 * @returns {Object} Category theme tokens
 */
export function getCategoryTheme(category) {
  if (!category || typeof category !== 'string') {
    return FALLBACK_THEME;
  }
  return CATEGORY_THEMES[category.trim()] || FALLBACK_THEME;
}

