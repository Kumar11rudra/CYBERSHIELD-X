/**
 * Normalization lookup mapping authoritative CATEGORIES constants to their theme keys
 */
const CATEGORY_CANONICAL_MAP = {
  'Authentication & Identity Security': 'Authentication & Identity',
  'Container & Kubernetes Security': 'Container & Kubernetes',
  'DevSecOps / Supply Chain Security': 'DevSecOps / Supply Chain',
  'Binary / Reverse Engineering': 'Binary / Reverse Eng.',
  'Social Engineering / Phishing Defense': 'Phishing Defense',
  'Compliance / Security Posture': 'Compliance / Posture',
  'Utilities / Encoding / Cryptography': 'Utilities / Crypto',
};

/**
 * Safely resolves the visual theme for any given category string.
 * Returns DEFAULT_TOOL_THEME when the category is undefined, empty, or unknown.
 *
 * @param {string} [category]
 * @returns {typeof DEFAULT_TOOL_THEME}
 */
export function getCategoryTheme(category) {
  if (!category || typeof category !== 'string') {
    return DEFAULT_TOOL_THEME;
  }
  const trimmed = category.trim();
  if (CATEGORY_THEMES[trimmed]) {
    return CATEGORY_THEMES[trimmed];
  }
  const mapped = CATEGORY_CANONICAL_MAP[trimmed];
  if (mapped && CATEGORY_THEMES[mapped]) {
    return CATEGORY_THEMES[mapped];
  }
  return DEFAULT_TOOL_THEME;
}

